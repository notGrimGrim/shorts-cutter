"""Скользящие окна по всей длине ролика. Это единица нарезки.

Зачем понадобилось. Раньше единицей была пара «вопрос → ответ»: конец
задавала следующая реплика ведущего. Граница была не про мысль, а про то,
когда прозвучал следующий вопрос — и когда ответ на самом деле продолжался
дальше (вопрос ведущего был «в тему», не сменой темы), пару всё равно резало
по нему. Ринат посмотрел 21 готовый файл, забраковал 11 из 16, по которым
высказался, — и почти все жалобы одни и те же: «оборвалось рано». Метрика
обрывов предложений (5%) здесь не годится: она проверяла, закончено ли
ПРЕДЛОЖЕНИЕ, а не мысль, и молчала про все эти случаи.

Единица нарезки заменена целиком. Окно теперь не привязано к вопросу и не
привязано к тому, кто говорит: раньше пара обязана была начинаться с реплики
ведущего, чтобы иметь границу, и это резало вопрос ведущего в середине темы
как будто он открывает новую. Окно строится по устройству речи — паузам
и концам предложений, — а не по ролям.

Устройство модуля: офлайн-эвристика (окна между паузами, коридор
длительности) и снаппинг границ по предложениям (`_snap_start`/
`_fit_end`): конец клипа — договорённая мысль, а не любая пауза.

Что делает модуль:

1. режет расшифровку на предложения (как раньше — `sentences()`);
2. на каждом предложении, начатом заново (после точки/!/?/… предыдущего),
   пробует построить окно 25–105 с: конец ищет среди концов предложений
   внутри коридора — сначала с настоящей точкой/!/?, потом с любым
   завершением фразы;
3. не находит такого конца — окно не строится вовсе, разговор в этом месте
   не режется криво (главное правило: обрыв не лечится плохой границей);
4. плашка: заголовок главы, чья часть в окне больше остальных, — или, если
   глав у ролика нет, первый вопрос ведущего в начале окна, — или пусто;
5. оценивает окна своими силами, без всякой модели (как раньше — `rate()`).

Оценка здесь по-прежнему грубая и нужна как запасной путь: когда модель
доступна, сравнивать хуки между собой должна она (см. think.rank). Но
программа обязана работать и без сети, и без ключа — тогда порядок задаёт
этот счёт.

Окна одного ролика по построению плотно перекрываются — соседние
предложения почти всегда дают соседние, почти одинаковые окна. Отбор,
какое из перекрывающихся окон в итоге войдёт в нарезку, — не задача этого
модуля: см. think.select и сопроводительную записку в WORKLOG.md.
"""

