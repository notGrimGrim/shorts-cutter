LOW = 25.0
HIGH = 120.0

# Целевая длительность без ускорения — используется только в своём счёте
# (rate()), чтобы окно ближе к 90 с не проигрывало окну впритык к HIGH.
TARGET = 90.0

# Сколько слов в предложении считать пределом. В расшифровке попадаются
# куски по сотне слов без единой точки — по ним не выбрать границу.
LONG_SENTENCE = 40

# Знаки, которыми предложение вообще может кончаться — своим (настоящим)
# концом, а не принудительным разрывом sentences() по счётчику слов.
_ENDS = (".", "!", "?", "…")

# Из них — только те, что значат «мысль договорена», а не «оборвалась».
# Многоточие в _ENDS входит (predложение им заканчивается), но не сюда:
# «…с тем, что у тебя…» — это обрыв, а не финал, и как граница годится
# только вторым сортом, когда точки и вопроса рядом вообще не нашлось.
_TIER1 = (".", "!", "?")

# Сколько секунд от начала окна просматриваем в поисках вопроса ведущего
# для плашки, когда глав у ролика нет. Открывающая реплика темы — это
# начало окна, а не произвольное место внутри него.
HOOK_OPEN = 20.0

# Вопросительные слова: по ним видно вопрос даже там, где расшифровка
# забыла поставить знак. Whisper теряет «?» примерно в каждом пятом вопросе.
# Используется для оценки хука (pairs.rate) — там «Как обмануть систему»
# в заголовке действительно хороший, кликабельный вопрос.
_ASKING = frozenset("""
почему зачем как сколько когда где куда откуда что кто какой какая какие
чем кому кого чего правда ли стоит нужно можно бывает часто расскажи
скажи объясни поясни
""".split())

# Подмножество для is_question(): «что», «как», «можно», «ли», «какой»,
# «сколько» в разговоре гораздо чаще служат союзом придаточного или частью
# устойчивого оборота, чем вопросом. Прогон обеих расшифровок целиком
# показал: каждое мягкое срабатывание на этих словах («это как раз...»,
# «понимаю, что...», «так можно дать...», «вряд ли...», «видно, на какой...»)
# оказалось ложным и резало ответ до того, как он начался, — «Костыли и
# туннели» обрывались вопросом ведущего, «На что делится ИБ» терялась треть
# объяснения. Ни одного настоящего вопроса на этих словах без «?» не нашлось
# ни разу — оставлены только слова, которые почти не бывают ничем другим.
_ASKING_SOFT = frozenset("""
почему зачем когда где куда откуда кто правда стоит нужно бывает часто
расскажи скажи объясни поясни
""".split())

# Слова, с которых вопрос звучит как продолжение чужой мысли, а не как
# начало разговора. Такой хук в плашке непонятен. Тот же список нужен и
# _orphaned() ниже: причинные союзы «потому»/«поэтому» — тот же случай
# «продолжение», просто не местоимением, а связкой.
_DANGLING = frozenset("""
он она они его её ее их это этот эта эти то тот та те там тут тогда
такой такая такие так этим этих этому потом дальше ещё еще потому поэтому
""".split())

# Разрыв в словах перед входом, после которого предложению, начатому с
# _DANGLING, доверия нет: Whisper иногда молчит там, где на самом деле шла
# речь (шум, ливень, наложение голосов — не тишина), и первое дошедшее до
# расшифровки слово после такой дыры выглядит началом нового предложения
# просто потому, что предыдущее кончилось настоящей точкой. Обычная пауза
# в разговоре короче на порядок (проверено на 4 роликах — свои паузы не
# длиннее ~8с, за одним известным исключением уже без _DANGLING-начала);
# 15с — с запасом выше любой такой паузы и с запасом ниже обеих реальных
# находок (20.1с и 26.5с).
ENTRY_GAP_SUSPECT = 15.0

# «Это [X], которое / при котором / за которым...» — самостоятельное
# определение термина, а не отсылка к обрубленному контексту: «это» тут
# смотрит вперёд, на то, что определяется в этом же предложении, а не назад.
# Живой случай — «Айсберг ДЕПРЕССИИ» (BLA5gR_D230): ролик перечисляет термины
# как «[Заголовок]. [22.5с тишины — на экране только подпись] Это
# психологическое состояние, при котором человек не верит в собственные
# успехи...». Без этого исключения _orphaned() ниже видел ровно ту же
# комбинацию, что и в Этапе 13 (разрыв шире ENTRY_GAP_SUSPECT + предложение
# начато словом из _DANGLING) и снимал вход — но здесь разрыв настоящий
# (пауза самого видео, не дыра в распознавании), а «это» не продолжение,
# а начало новой, самодостаточной мысли. Подтверждено на 3 живых находках
# в одном ролике (см. WORKLOG) — везде один и тот же оборот.
_DEFINITION = re.compile(r"^это\b.{0,60}?\bкотор", re.IGNORECASE)

# Та же связка «[Заголовок]. Это [X], которое/при котором...», но для
# другой задачи: не разрешить вход после дыры (см. _DEFINITION выше), а
# найти ГРАНИЦУ следующей темы внутри уже строящегося окна (см. _fit_end,
# Этап 18 — _fit_end() берёт самый дальний конец в коридоре, не зная, что
# такое тема, и залезает в соседний термин на ленте списка терминов).
# Отдельная константа, не переиспользую _DEFINITION: бюджет до «котор»
# шире (110 вместо 60 — «Синдром Амока» не укладывался в 60), и заголовок
# перед «это» может быть слитен с определением без точки и капсом
# («КЛИНИЧЕСКАЯ ЭЛИКОНТРОПИЯ Это редкое психическое расстройство...») —
# такого раньше не было ни у одного случая _orphaned(), трогать тот путь
# незачем. Сам регэксп проверен на всех 15 роликах с сохранённым
# whisper-medium.json: 10 новых срабатываний, все — в BLA5gR_D230 (лента
# терминов), ни одного на остальных 14. Но голого совпадения мало — тот
# же оборот «это X, которое» ловит и обычную реплику интервью («Да,
# Дмитрий, все верно. Это именно плагин, который...»), поэтому как
# ГРАНИЦА (не вход) доверяем не всякому совпадению — см. _trustworthy.
_TOPIC_MARK = re.compile(r"^(?:[А-ЯЁ]{2,}\s+){0,4}[Ээ]то\b.{0,110}?[Кк]отор")

# Заголовок слит с определением без пробела, самим капсом — структурно
# однозначный признак («КЛИНИЧЕСКАЯ ЭЛИКОНТРОПИЯ Это редкое...»), не
# нужно смотреть на соседнее предложение вообще.
_CAPS_PREFIX = re.compile(r"^(?:[А-ЯЁ]{2,}\s+){1,4}")

# Сколько слов в предложении, чтобы считать его кандидатом в «голый
# заголовок» («Синдром амока.», «Хикикамори.») — длины одной мало, см.
# _looks_like_title.
_TITLE_WORDS = 5

# Разрыв перед предположительным заголовком в паре _own_marker (entry —
# короткая фраза, entry+1 — её определение), ниже которого считаем их
# одной парой. Только для этого направления: у самой ГРАНИЦЫ (см.
# _trustworthy/_topic_ceiling) разрыв между заголовком и определением
# бывает и настоящей паузой в 20+с (см. _DEFINITION) — гэп там не
# ограничиваю.
_TITLE_GAP = 5.0

# Короткая реплика разговора — не заголовок. «Да, Дмитрий, все верно.»/
# «И да.» — те же 2-5 слов, что и «Синдром амока.», но это ответ
# собеседника, не подпись термина. Без этого фильтра _looks_like_title
# ниже путает интервью с лентой терминов и режет окна интервью без
# всякой смены темы (см. WORKLOG, Этап 19 — живые случаи на
# UyYnqtsE6e8/cWIgmXxB51o/CdcVjxzcmwc).
_FILLER = frozenset("да нет ну вот ага угу точно ясно хорошо окей "
                     "кстати слушай смотри скажи и а".split())

# Признаки конкретики в ответе: числа, перечисления, примеры. Ровно то,
# отсутствие чего Ринат назвал «нет ответа на вопрос из плашки».
#
# Причинно-следственные связки — отдельным пластом: ответ на «почему» по
# природе объясняет причину, а не считает в цифрах, и без этого пласта
# содержательный разбор («тормозят, потому что на каждый чих нужно
# согласование») получал те же баллы, что пустая отговорка без единого слова
# по существу.
_FACT = re.compile(
    r"\d|процент|тысяч|миллион|во-первых|во-вторых|например|конкретно|"
    r"допустим|случа|пример|"
    r"потому что|поэтому|из-за|зависит|если\b.{0,20}\bто\b",
    re.IGNORECASE,
)

# Реклама и обращения к зрителю: в шортс не годятся ни при каком счёте.
_JUNK = re.compile(
    r"подпис|лайк|коммент|ссылк[аи] в описании|промокод|реклам|канал",
    re.IGNORECASE,
)

# Знакомство и прощание. Первая глава ролика почти всегда начинается с
# «здравствуйте, меня зовут» — в шортсе это пустые двадцать секунд.
_GREETING = re.compile(
    r"здравствуй|добрый день|добрый вечер|привет|меня зовут|представ(ь|ьс|тес)|"
    r"спасибо, что пришл|до свидания|всем пока",
    re.IGNORECASE,
)


@dataclass
class Sentence:
    """Предложение расшифровки: время, текст и место в потоке слов."""

    number: int
    start: float
    end: float
    text: str
    first: int
    last: int

    @property
    def duration(self):
        return self.end - self.start


@dataclass
class Pair:
    """Окно ролика — то, из чего собирается шортс.

    hook — то, что встанет надписью в кадр: заголовок главы или вопрос
    ведущего, которым окно открывается. Пустая строка — плашку сочинит
    downstream-фолбэк (chapters.from_speech/from_keys в cut.py), это не
    работа этого модуля.

    chapter — заголовок главы, если хук взят из неё; иначе пусто. Отдельное
    поле, а не признак пустого/непустого hook, потому что think.rank() по
    нему решает, можно ли переписывать надпись моделью (главу — нельзя,
    это уже авторский текст).
    """

    hook: str
    start: float
    end: float
    text: str
    chapter: str = ""
    score: float = 0.0

    @property
    def duration(self):
        return self.end - self.start

    @property
    def title(self):
        return self.hook


def sentences(words):
    """Расшифровка, разбитая на предложения с таймкодами."""
    found, current = [], []

    def close():
        if not current:
            return
        first, last = current[0], current[-1]
        found.append(Sentence(
            number=len(found) + 1,
            start=words[first].start,
            end=words[last].end,
            text=" ".join(words[i].text for i in range(first, last + 1)),
            first=first,
            last=last,
        ))
        current.clear()

    for index, word in enumerate(words):
        current.append(index)
        if word.text.endswith(_ENDS) or len(current) >= LONG_SENTENCE:
            close()
    close()

    return found


def is_question(sentence, strict=False):
    """Вопрос ли это.

    Знака вопроса мало: расшифровка ставит его не всегда. Поэтому вторым
    признаком берём короткую реплику с вопросительным словом в самом начале —
    так ведущий и спрашивает: «а сколько платят на старте».

    strict — доверять только знаку вопроса. Нужно там, где ошибка дорога:
    на мягком признаке «Вот у меня почему-то получилось проходить дважды»
    засчиталось за вопрос, и шортс начался с середины чужой мысли.
    """
    text = sentence.text.strip()
    if "?" in text:
        return True
    if strict:
        return False

    words = [w.strip(".,!?:;«»\"'()").lower() for w in text.split()]
    if not 2 <= len(words) <= 14:
        return False

    # «почему-то», «как-то», «что-то» — не вопросы, а слова-паразиты живой
    # речи, и расшифровка разрывает их на два слова.
    head = words[:3]
    for place, word in enumerate(head):
        if word in _ASKING_SOFT and not (place + 1 < len(words)
                                    and words[place + 1].startswith("-")):
            return True
    return False


def _hook_text(sentence):
    """Вопрос, приведённый к виду надписи."""
    text = re.sub(r"\s+", " ", sentence.text).strip(" -–—")
    text = re.sub(r"^(ну|вот|слушай|смотри|скажи|а|и|да)\b[,\s]*", "", text,
                  flags=re.IGNORECASE).strip()
    return text[:1].upper() + text[1:] if text else ""


def _leads_nowhere(hook):
    """Хук, который сам по себе непонятен: «а он тогда что сделал?»."""
    words = [w.strip(".,!?:;«»\"'()").lower() for w in hook.split()]
    return bool(words) and words[0] in _DANGLING


def _text_between(words, start, end):
    return " ".join(w.text for w in words if start <= w.start < end)


def _orphaned(lines, index):
    """Вход после дыры в расшифровке, а не после настоящей паузы автора.

    Дыра сама по себе не запрещена — длинная пауза бывает и у живого
    разговора. Запрещена комбинация: дыра шире ENTRY_GAP_SUSPECT И
    предложение после неё само звучит как продолжение (_leads_nowhere,
    тот же признак, что и для хука). Одно первое слово «потому что» без
    большой дыры перед ним — обычное начало объяснения, ничем не хуже
    любого другого (`_FACT` в rate() его за это же и хвалит), поэтому
    признак связки одна, без дыры, окно не запрещает.

    Отдельное исключение — _DEFINITION: «Это [X], которое/при котором...»
    после дыры тоже начинается с признака из _DANGLING («это»), но это не
    продолжение, а самостоятельное определение термина. См. комментарий
    у _DEFINITION.
    """
    if index == 0:
        return False
    gap = lines[index].start - lines[index - 1].end
    if gap <= ENTRY_GAP_SUSPECT:
        return False
    text = lines[index].text
    if _DEFINITION.match(text.lstrip()):
        return False
    return _leads_nowhere(text)


def _entries(lines):
    """Индексы предложений, с которых можно начать окно.

    Первое предложение ролика — вход всегда: тишина перед ним есть по
    определению, начинать больше не с чего. Дальше вход открывается, только
    если предыдущее предложение кончилось по-настоящему — точкой, «!», «?»
    или «…». Обычная пауза между словами в счёт не идёт: sentences() рвёт
    расшифровку ещё и по счётчику слов (LONG_SENTENCE), когда в тексте сто
    слов подряд без единого знака, и без этой проверки такой принудительный
    разрыв сходил бы за начало новой мысли посреди чужой.

    Настоящая точка перед входом тоже не всегда значит «начало мысли»: см.
    _orphaned — если перед предложением дыра шире ENTRY_GAP_SUSPECT, а само
    оно начинается со слова-продолжения, точка в конце предыдущего — не
    конец мысли, а конец того, что вообще дошло до расшифровки.
    """
    found = [0]
    for index in range(1, len(lines)):
        if (lines[index - 1].text.rstrip().endswith(_ENDS)
                and not _orphaned(lines, index)):
            found.append(index)
    return found


def _topic_marks(lines):
    """Индексы предложений, с которых начинается определение нового термина.

    Не про вход в окно (см. _entries/_orphaned) — про то, где внутри уже
    строящегося окна лежит граница СЛЕДУЮЩЕЙ темы, чтобы _fit_end ниже мог
    остановиться до неё, а не перескочить самым дальним концом (предел
    диагностирован в Этапе 18, чинится здесь, в Этапе 19).
    """
    return {i for i, line in enumerate(lines) if _TOPIC_MARK.match(line.text.lstrip())}


def _looks_like_title(lines, index):
    """Похоже ли предложение на заголовок-подпись, а не на реплику разговора.

    Длины одной мало: «Синдром амока.» и «Да, Дмитрий, все верно.» — оба
    ≤5 слов, но второе — ответ собеседника в интервью, не подпись термина
    (живой ложный случай, см. _FILLER). Не вопрос (вопрос — реплика, не
    заголовок) и не начинается с вводного слова разговора.
    """
    text = lines[index].text.strip()
    if is_question(lines[index]):
        return False
    words = [w.strip(".,!?:;«»\"'()").lower() for w in text.split()]
    if not words or len(words) > _TITLE_WORDS:
        return False
    return words[0] not in _FILLER


def _own_marker(lines, entry, topics):
    """Если вход сам открывает тему — индекс её определения, иначе None.

    Вход считается «своим» для темы в двух случаях: он и есть определение
    (entry сам в topics — «Это состояние, при котором...» без отдельного
    заголовка), либо entry — короткий заголовок-подпись прямо перед
    определением («Синдром амока.» → «Это редкое... состояние, при
    котором...», разрыв меньше _TITLE_GAP). Без этого разбора _fit_end
    принял бы собственное определение темы за ГРАНИЦУ, которую нужно
    обрезать, — и окно обрывалось бы, не начавшись.
    """
    if entry in topics:
        return entry
    following = entry + 1
    if (following < len(lines) and following in topics
            and _looks_like_title(lines, entry)
            and lines[following].start - lines[entry].end < _TITLE_GAP):
        return following
    return None


def _trustworthy(lines, mark):
    """Можно ли доверять маркеру как ГРАНИЦЕ чужой темы (не как входу).

    Голого совпадения _TOPIC_MARK мало — та же связка «Это X, которое...»
    ловит и обычную реплику разговора («Да, Дмитрий, все верно. Это
    именно плагин, который...», живой случай на cWIgmXxB51o) без всякой
    смены темы. Доверяем только двум структурным случаям: заголовок слит
    с определением капсом без пробела («КЛИНИЧЕСКАЯ ЭЛИКОНТРОПИЯ Это
    редкое...») — или перед определением стоит короткое самостоятельное
    предложение-подпись, не вводное слово и не вопрос (_looks_like_title).
    Проверено на всех 15 роликах — без фильтра три ложных маркера
    (UyYnqtsE6e8, cWIgmXxB51o, CdcVjxzcmwc, везде реплика разговора) резали
    окна интервью без всякой смены темы; с фильтром — ноль ложных, ни один
    нужный случай BLA5gR_D230 не потерян (WORKLOG, Этап 19).
    """
    if _CAPS_PREFIX.match(lines[mark].text.lstrip()):
        return True
    return mark > 0 and _looks_like_title(lines, mark - 1)


def _topic_ceiling(lines, boundary):
    """Последний индекс, включать который в окно ещё безопасно.

    boundary — начало чужой темы, уже подтверждённое _trustworthy. Если
    ему предшествует ещё один короткий заголовок-подпись (тот же признак,
    _looks_like_title, без ограничения на разрыв — пауза перед подписью
    бывает и настоящей, в 20+с, см. _DEFINITION) — окно не должно
    захватывать и его: клип не должен обрываться на чужом заголовке без
    единого слова по теме.
    """
    ceiling = boundary
    while ceiling > 0 and _looks_like_title(lines, ceiling - 1):
        ceiling -= 1
    return ceiling


def _chapter_bound_index(lines, marks, start_time, low):
    """Индекс первого предложения на границе СЛЕДУЮЩЕЙ авторской главы.

    Та же роль, что и boundary из _topic_marks (где остановиться, чтобы не
    перескочить самым дальним концом в чужую тему) — но граница здесь не
    эвристика по тексту, а точный таймкод из marks (реальные главы ролика,
    из метаданных). Живой случай (CdcVjxzcmwc): окно «КАК РАСКРЫТЬ СКОБКИ?»
    (508.34–627.63с) залезало на 42.6с в следующую главу «ФОРМУЛЫ. НО
    СПЕРВА АНЕКДОТ» (585.0–764.0с) — ровно на завязку анекдота, без
    развязки (она звучит на ~74с дальше границы). marks были доступны
    build() всегда — просто не доходили до _fit_end, только до _plashka.

    Вход не всегда лежит в той главе, которую потом покажет _majority_chapter
    (у неё большинство длительности окна, не обязательно первые секунды):
    тот же живой случай начинается за 11.6с до конца ЕЩЁ ПРЕДЫДУЩЕЙ главы,
    и первая попавшаяся граница (её собственный конец) — не та, что нужна,
    это всё ещё, по сути, начало окна, а не выход из его темы. Поэтому
    пропускаем главы, в которых от входа остаётся меньше low секунд.
    """
    if not marks:
        return None
    for mark in marks:
        if mark.end <= start_time:
            continue
        if mark.end - max(start_time, mark.start) < low:
            continue
        for index, line in enumerate(lines):
            if line.start >= mark.end:
                return index
        return None
    return None


def _fit_end(lines, entry, low, high, topics=frozenset(), marks=()):
    """Индексы предложений, которыми по-честному может кончиться окно.

    Порядок предпочтений — сначала точка, «!» или «?» (мысль договорена),
    потом любой конец предложения в коридоре, включая «…» и место, где
    sentences() резала по счётчику слов, а не по знаку. Из подходящих в
    каждом уровне берём самый дальний: он даёт самую длинную договорённую
    мысль, какая умещается в коридор, — а не первую попавшуюся короткую.
    Ринат жаловался ровно на обратное: клипы обрывались раньше, чем мысль
    договаривалась. Этот, самый дальний конец, возвращается всегда (как
    раньше, вызывающий получает список из одного элемента) — эта функция
    ничего не отбирает у build(), только предлагает.

    Ни одного конца предложения в коридоре нет вовсе — пустой список, окно
    не строится вовсе. Обрыв на полуслове негодной границей не лечится:
    это и есть главное правило нарезки, ради которого вся эта функция
    существует.

    Добавка (Этап 19, предел найден в Этапе 18) — если внутри коридора
    видна граница СЛЕДУЮЩЕЙ темы (topics, см. _topic_marks) и до неё есть
    законный конец не короче low, в список добавляется ВТОРОЙ, более
    короткий кандидат — окно, которое останавливается перед чужой темой, а
    не перескакивает в неё самым дальним концом (см. WORKLOG, Этап 18,
    «Кодокуши»/«Психогенная смерть»). Не замена дальнему концу, а
    дополнительный кандидат: у «Самосаботажа» (см. WORKLOG, Этап 18)
    дальний конец, пересекающий тему-соседку, — и есть тот самый
    одобренный вариант, обрезать его нельзя. Оставляю оба, выбор между
    ними — не работа этого модуля (см. build()/think.select()).
    """
    start = lines[entry].start
    own = _own_marker(lines, entry, topics)
    search_from = (own if own is not None else entry) + 1

    boundary = None
    strict, loose = [], []
    for index in range(entry, len(lines)):
        if (boundary is None and index >= search_from and index in topics
                and _trustworthy(lines, index)):
            boundary = index
        duration = lines[index].end - start
        if duration > high:
            break
        if duration < low:
            continue
        text = lines[index].text.rstrip()
        if text.endswith(_ENDS):
            loose.append(index)
            if text.endswith(_TIER1):
                strict.append(index)

    pool = strict or loose
    if not pool:
        return []
    far = max(pool)
    ends = [far]

    # Реальная граница главы — надёжнее эвристики _topic_marks там, где
    # обе нашлись (она не гадает по тексту, а знает точный таймкод) —
    # поэтому при конфликте берём более раннюю (более осторожную) из двух.
    chapter_bound = _chapter_bound_index(lines, marks, start, low)
    if chapter_bound is not None and (boundary is None or chapter_bound < boundary):
        boundary = chapter_bound

    if boundary is not None:
        ceiling = _topic_ceiling(lines, boundary)
        narrow = [i for i in strict if i < ceiling] or [i for i in loose if i < ceiling]
        if narrow:
            near = max(narrow)
            if near != far:
                ends.append(near)

    return ends


def _majority_chapter(marks, start, end):
    """Глава, которой в окне досталось больше секунд, чем остальным.

    Окно вправе пересекать границу главы — свобода границ важнее, чем
    точное попадание в одну тему (см. модуль think.py и его комментарий
    про то же самое). Поэтому здесь не «окно внутри главы», а голое
    большинство: какая глава наложилась на окно сильнее прочих.
    """
    best, best_overlap = None, 0.0
    for mark in marks:
        overlap = min(end, mark.end) - max(start, mark.start)
        if overlap > best_overlap:
            best, best_overlap = mark, overlap
    return best


def _opening_question(lines, entry, exit_index, start):
    """Первый вопрос ведущего в первых HOOK_OPEN секундах окна, если есть."""
    for line in lines[entry:exit_index + 1]:
        if line.start >= start + HOOK_OPEN:
            break
        if not is_question(line):
            continue
        hook = _hook_text(line)
        if hook and not _leads_nowhere(hook):
            return hook
    return ""


def _plashka(lines, marks, entry, exit_index, start, end):
    """Что встанет плашкой: глава — вопрос ведущего — пусто, в этом порядке.

    Пустая плашка — не брак: её дальше чинит фолбэк в cut.py._banner
    (chapters.from_speech/from_keys/video_title). Сочинять надпись самим —
    не работа этого модуля.
    """
    if marks:
        chapter = _majority_chapter(marks, start, end)
        if chapter:
            return chapter.title, chapter.title
        return "", ""

    return _opening_question(lines, entry, exit_index, start), ""


def build(words, marks=(), low=LOW, high=HIGH):
    """Скользящие окна по всей длине ролика.

    Один проход по предложениям: на каждом законном входе (см. _entries)
    пробуем достроить окно длиной low..high секунд, конец которого — тоже
    конец предложения (см. _fit_end). Не вышло — вход не даёт окна вовсе,
    без разрезания и без растяжения (правило 5 задания).

    Никакой привязки к тому, кто говорит: вход — любое предложение с
    законным началом, а не только реплика ведущего. Вопрос ведущего внутри
    окна не мешает и не помогает — окно решает не про это.

    Соседние входы почти всегда дают соседние, сильно перекрывающиеся окна:
    это и есть «скользящие окна», отбор среди них — не здесь. С Этапа 19
    один вход иногда даёт ДВА окна (см. _fit_end) — обычное, самое дальнее,
    и короче, если рядом видна граница следующей темы: оба остаются
    кандидатами, короче не заменяет длиннее.
    """
    if not words:
        return []

    lines = sentences(words)
    if not lines:
        return []

    marks_sorted = sorted(marks, key=lambda mark: mark.start) if marks else ()
    topics = _topic_marks(lines)

    found = []
    for entry in _entries(lines):
        for exit_index in _fit_end(lines, entry, low, high, topics, marks_sorted):
            start, end = lines[entry].start, lines[exit_index].end
            hook, chapter = _plashka(lines, marks_sorted, entry, exit_index, start, end)
            found.append(Pair(
                hook=hook,
                start=round(start, 2),
                end=round(end, 2),
                text=_text_between(words, start, end),
                chapter=chapter,
            ))

    return found


def plan(words, marks=(), terms=(), energy=None, count=3, video_title="",
         source="", brain=True, on_note=None):
    """Полный путь: окна → свой счёт → отбор моделью.

    Одна точка сборки на всех: и командная строка, и окно, и мастер зовут
    её же. Возвращает готовые к нарезке окна — уже с надписями, где надпись
    нашлась.

    brain=False значит «не звать модель»: порядок задаёт свой счёт. Так же
    выйдет и само собой, если ни Groq, ни Ollama недоступны.
    """
    talk = on_note or (lambda note: None)

    built = build(words, marks)
    if not built:
        return []

    rated = rate(built, words, energy, terms)
    talk(f"окон-кандидатов: {len(rated)}")

    if brain:
        from . import think  # локально: без модели этот модуль не нужен

        return think.select(rated, video_title, count, on_note=talk,
                             words=words, source=source)

    return rated[:count]


# ── свой счёт, когда модели нет ───────────────────────────────────────────

def rate(pairs, words, energy=None, terms=()):
    """Оценка окон без всякой модели: чем цепляет вопрос и есть ли ответ.

    Это запасной путь. Он не отличит бойкий вопрос от банального — на это
    нужен тот, кто понимает смысл, — но выбирает заметно лучше случайного:
    вопрос с вопросительным словом, ответ с числами и примерами, живой звук
    и слова, вокруг которых крутится весь ролик.
    """
    if not pairs:
        return []

    energy = _energy_lookup(energy)
    weights = dict(zip(range(len(words)), keywords.weights(words))) if words else {}
    loudest = _loudness(words, energy)
    keys = [k.lower()[:6] for k in terms if len(k) > 3]

    for pair in pairs:
        pair.score = round(_rate_one(pair, words, weights, loudest, keys, energy), 3)

    return sorted(pairs, key=lambda p: p.score, reverse=True)


def _energy_lookup(energy):
    """Приводит громкость к одному виду: словарь «индекс слова -> 0..1».

    audio.per_word() отдаёт список позиционно по словам — так его получают
    app.py и gui.py, зовущие plan() напрямую. cut.py на своей стороне уже
    заворачивает список в dict(enumerate(...)), потому что дальше по коду
    везде вызывается energy.get(index, ...). Разбирать оба вида здесь, один
    раз, вместо того чтобы требовать этого от каждого вызывающего — иначе
    тот, кто скопирует вызов из app.py, получит AttributeError на списке.
    """
    if not energy:
        return {}
    if isinstance(energy, dict):
        return energy
    return dict(enumerate(energy))


def _loudness(words, energy):
    """Средняя громкость по ролику, чтобы сравнивать с ней куски."""
    if not energy:
        return None
    values = [energy.get(index, 0.0) for index in range(len(words))]
    live = [v for v in values if v > 0]
    return sum(live) / len(live) if live else None


def _rate_one(pair, words, weights, loudest, keys, energy):
    hook = pair.hook.lower()
    text = pair.text.lower()
    score = 0.0

    # Вопросительное слово в хуке: обещание, за которым хочется остаться.
    asking = [w.strip(".,!?:;«»\"'()") for w in hook.split()]
    if _ASKING.intersection(asking):
        score += 1.2

    # Хук в две-три строки читается, длиннее — нет.
    if 4 <= len(asking) <= 14:
        score += 0.6

    # Конкретика в ответе — то самое «есть ли ответ на плашку».
    facts = len(_FACT.findall(pair.text))
    score += min(facts, 4) * 0.45

    # Ключевые слова ролика: разговор по делу, а не отступление.
    if keys:
        hit = sum(1 for key in keys if key in text)
        score += min(hit / max(len(keys), 1) * 3.0, 1.2)

    # Живой звук: смех, повышенный голос. Считается только если дорожку
    # вообще разбирали.
    if loudest:
        inside = [i for i, w in enumerate(words) if pair.start <= w.start < pair.end]
        if inside:
            own = sum(energy.get(i, 0.0) for i in inside) / len(inside)
            score += min(own * 1.5, 0.9)

    # Длина: ближе к формату — лучше, но выше TARGET бонус не обнуляем
    # совсем — длинная содержательная история не должна проигрывать
    # короткой пустой только за то, что она ближе к HIGH.
    if pair.duration <= TARGET:
        score += 0.7
    else:
        score += 0.4

    # Реклама и обращения к зрителю не годятся ни при каком счёте.
    if _JUNK.search(pair.text):
        score -= 3.0

    # Знакомство в начале ролика: двадцать секунд «здравствуйте, меня
    # зовут» — это не шортс. Смотрим только начало куска: то же слово
    # в середине разговора ничего не портит.
    if _GREETING.search(pair.text[:220]):
        score -= 2.0

    # Глава — признак, что автор сам считает это отдельной темой.
    if pair.chapter:
        score += 0.5

    return max(score, 0.0)
