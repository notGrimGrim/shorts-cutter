"""Главы ролика — авторская разметка того, что где происходит.

Это самый честный сигнал из доступных: границы тем расставил человек,
который снимал видео, а заголовок главы он писал, чтобы зацепить зрителя.
Статистика по словам такое не угадает.

Тепловую карту пересмотров («most replayed») YouTube для этого канала не
отдаёт — проверено на пяти роликах, поэтому опираемся на главы.
"""

import re
from dataclasses import dataclass

# Служебные главы: там нет содержания, только вступление и прощание.
SKIP = (
    "вступл", "интро", "начало", "привет", "заверш", "конец", "итог",
    "заключ", "реклам", "спонсор", "анонс", "подпис", "таймкод",
)

# Заголовок, который цепляет: спор, отрицание, обещание, обращение к зрителю.
SHARP = (
    "почему", "зачем", "как ", "что делать", "ошибк", "провал", "миф",
    "правд", "вранн", "ври", "лож", "секрет", "никогда", "нельзя",
    "не всегда", "не берут", "не может", "против", "вместо", "а не",
    "сколько", "стоит ли", "хватит", "забудь", "перестань",
)

_WORD = re.compile(r"[^\W\d_]+", re.UNICODE)


# Обещает ли заголовок ответ, здесь больше не считается. Признак был у главы
# отдельным полем (Chapter.asks) и не читался никем: scan.find про обещание
# спрашивает иначе — там любой заголовок главы уже считается обещанием
# (см. promised), потому что он висит в кадре весь шортс.


@dataclass
class Chapter:
    start: float
    end: float
    title: str
    weight: float

    @property
    def duration(self):
        return self.end - self.start


def _sharpness(title):
    """Насколько заголовок сам по себе тянет посмотреть. 0..1."""
    low = title.lower()
    score = 0.0

    if low.rstrip().endswith("?"):
        score += 0.35
    if re.search(r"\d", title):
        score += 0.25
    if re.search(r"\bне\b|\bнет\b|\bбез\b", low):
        score += 0.2
    if any(mark in low for mark in SHARP):
        score += 0.3
    if re.search(r"\bты\b|\bтебе\b|\bтвой\b|\bвы\b", low):
        score += 0.15

    # Слишком длинный заголовок в кадр не влезет и крючком не работает.
    length = len(_WORD.findall(title))
    if length > 9:
        score -= 0.2

    return max(0.0, min(score, 1.0))


def from_info(info, min_dur=40.0):
    """Достаёт главы из метаданных ролика. Пустой список, если их нет."""
    raw = info.get("chapters") or []
    found = []

    for item in raw:
        title = (item.get("title") or "").strip()
        start = item.get("start_time")
        end = item.get("end_time")
        if not title or start is None or end is None:
            continue

        low = title.lower()
        if any(mark in low for mark in SKIP):
            continue
        # В главу короче шортса просто не поместится окно нужной длины.
        if end - start < min_dur:
            continue

        found.append(Chapter(
            float(start), float(end), title, _sharpness(title)
        ))

    return found


_SENTENCE = re.compile(r"[^.!?…]+[.!?…]?")

# Разговорный зачин: на плашке он только занимает место. Отдельно ловим
# протяжные «ааэ» и «ээм» — расшифровка пишет их слитно и по-разному.
#
# Связки в начале («соответственно», «поэтому», «так вот») срезаем по той же
# причине, по какой не начинаем с них сам кусок: они отсылают к сказанному
# раньше, а в кадре этого «раньше» нет — надпись читается как обрывок.
_FILLER = re.compile(
    r"^(?:\W|[аэм]{1,4}|ну|вот|значит|короче|то есть|как бы|в общем|слушай|смотри"
    r"|угу|ага|да|нет|окей|о'кей"
    r"|соответственно|собственно|поэтому|потому что|потому|так вот|и вот"
    r"|в принципе|впринципе|допустим|скажем|кстати|причём|причем|типа"
    r"|получается|ведь|итак|таким образом|при этом|однако|хотя)\b[\s,]*",
    re.IGNORECASE,
)

# Слово, повторённое подряд: «на задачу там там сколько». Оговорка живой речи,
# в надписи выглядит опечаткой.
_STUTTER = re.compile(r"\b(\w+)(\s+\1\b)+", re.IGNORECASE | re.UNICODE)

# Предел обрезки надписи по умолчанию — общий для hook(), from_speech()
# и from_keys(). render.hook_size() умеет уменьшать кегль втрое (58 → 52 →
# 46) под то, что мы сюда передадим, но старый предел в 60 знаков был ниже
# того, что вообще может понадобиться уменьшать: тексты короче 60 всегда
# попадали в кегль 58, и две меньшие ступени не включались никогда.
#
# Реальный потолок проверен рендером в кадр (work/_hook-test), а не взят на
# глаз: две строки шрифтом 46 держат текст до ~92 знаков включительно, а на
# ~96 уже разваливаются в три строки с рассыпающейся плашкой — WrapStyle 0
# досчитывает перенос по пикселям поверх нашей разбивки по символам, и
# получаются лишние строка и отдельный кусок чёрной подложки под неё.
# 90 — с запасом ниже точки поломки.
#
# think.TITLE_LIMIT = 50 — другое число не по ошибке. Там модель сама
# переписывает надпись и её просят быть короче ради хлёсткости («не длиннее
# 50 знаков» в тексте промпта _RANK/_CHECK). Здесь же обрезаем то, что
# переписать некому — авторский заголовок главы или фраза из речи, — и режем
# только по границе оборота, а не выдумываем текст короче. Совпадать эти
# пределы не обязаны: один — предел вкуса для модели, другой — предел
# рендера для сырого текста.
HOOK_LIMIT = 90

MIN_WORDS = 3

# Сколько предложений куска вообще рассматриваем. Смысл не в экономии, а в
# том, что надпись должна объяснять начало шортса: фраза с последней минуты
# зрителя уже обманывает — он такого пока не слышал.
LOOK_AHEAD = 14

# Слишком длинное предложение — это не надпись, а абзац: в две строки не
# влезет, а обрезанное многоточием читается как оборванное.
TOO_LONG = 1.6

# Насколько дороже влезающая надпись обрезанной. Вес высокий намеренно:
# многоточие в кадре — прямой признак недоделки, зритель видит обрубок
# фразы. Лучше взять предложение попроще, но целое.
FIT = 1.4


def _fits(piece, limit):
    """Насколько надпись помещается в кадр. 1.0 — впору, 0.0 — абзац."""
    over = len(piece) / max(limit, 1)
    if over <= 1.0:
        return 1.0
    if over >= TOO_LONG:
        return 0.0
    return (TOO_LONG - over) / (TOO_LONG - 1.0)


def _about(piece, keys):
    """Доля ключевых слов куска, попавших в предложение. 0..1.

    Это и есть «по контексту»: из десятка фраз выбираем ту, где звучит то же,
    о чём кусок вообще. Сравниваем по началу слова — русский падеж меняет
    хвост, а «найму» и «найм» для нас одно и то же.
    """
    if not keys:
        return 0.0

    stems = {w.lower()[:6] for w in _WORD.findall(piece) if len(w) > 3}
    if not stems:
        return 0.0

    hit = sum(1 for key in keys if any(s.startswith(key.lower()[:6]) for s in stems))
    return min(hit / min(len(keys), 4), 1.0)


# Слова, которые показывают пальцем на то, чего в кадре нет: «а он тогда
# что сделал?». В самой беседе понятно, в надписи — нет. Для начала куска
# такой список есть в scan.DANGLING, но там он про речь, а тут про надпись,
# и требования строже: отсылка в первых двух словах убивает заголовок.
_DEIXIS = frozenset("""
он она оно они его её ее их им ими ему ей нём нем ней них
это этот эта эти то тот та те там тут туда оттуда тогда
такой такая такое такие так этим этих этому
""".split())

# Насколько дешевеет надпись, начатая с отсылки в никуда.
DEIXIS_PENALTY = 0.9

# Сколько первых слов проверяем на отсылку.
DEIXIS_HEAD = 2


def _dangling(piece):
    """Начинается ли надпись с отсылки к тому, чего в шортсе нет."""
    words = [w.lower() for w in _WORD.findall(piece)[:DEIXIS_HEAD]]
    return any(word in _DEIXIS for word in words)


def _score(piece, place, total, keys, limit):
    """Насколько предложение годится в надпись сверху."""
    score = 0.0

    if _dangling(piece):
        score -= DEIXIS_PENALTY

    # Произнесённый вслух вопрос — лучшая надпись, какая бывает: шортс на нём
    # и держится, и придумывать за автора не приходится.
    if piece.rstrip().endswith("?"):
        score += 1.0

    score += 0.7 * _sharpness(piece)
    score += 0.9 * _about(piece, keys)
    score += FIT * _fits(piece, limit)

    # Ближе к началу — лучше: надпись обещает то, что сейчас прозвучит.
    # Вес небольшой, иначе всё опять сведётся к первой фразе.
    score += 0.35 * (1.0 - place / max(total, 1))

    return score


def from_speech(text, limit=HOOK_LIMIT, keys=()):
    """Надпись для кадра, вытащенная из самой речи.

    Раньше здесь брался первый вопрос из первых пяти предложений — и на
    роликах без глав надписью становился случайный зачин вроде «ну смотри,
    я поясню». Теперь перебираем начало куска целиком и выбираем фразу,
    которая про то же, о чём кусок: вопрос, задевающая формулировка,
    ключевые слова куска, влезает в две строки.

    keys — ключевые слова куска (те же, что подсвечиваются в субтитрах).
    Без них выбор всё ещё работает, просто хуже отличает фразу по делу от
    гладкой, но пустой.
    """
    sentences = []
    for match in _SENTENCE.finditer(text or ""):
        piece = _tidy(match.group())
        if len(_WORD.findall(piece)) >= MIN_WORDS:
            sentences.append(piece)
        if len(sentences) >= LOOK_AHEAD:
            break

    if not sentences:
        return ""

    total = len(sentences)
    best = max(
        range(total),
        # При равенстве очков берём который раньше: max отдаёт первый
        # наибольший, поэтому порядок сохраняется сам.
        key=lambda index: _score(sentences[index], index, total, keys, limit),
    )
    return hook(sentences[best], limit)


def from_keys(keys, limit=HOOK_LIMIT):
    """Последняя опора: надпись из ключевых слов куска.

    Нужна затем, чтобы плашка сверху была всегда. Речь бывает такой, что
    целого предложения из неё не собрать — сплошной поток без точек, — и
    оставлять кадр без надписи хуже, чем написать «про найм и офферы».
    """
    picked = []
    for key in keys:
        word = str(key).strip()
        if len(word) > 2 and word.lower() not in {p.lower() for p in picked}:
            picked.append(word)
        if len(picked) == 2:
            break

    if not picked:
        return ""
    return hook("Про " + " и ".join(picked), limit)


# Сколько слов подряд считаем повторяющимся куском. Больше шести — это уже
# не заклинание в кадре, а две похожие мысли, и склеивать их нельзя.
_REPEAT_BLOCK = 6


def undouble(text, most=_REPEAT_BLOCK):
    """Схлопывает подряд идущие повторы: «А Б А Б А» → «А Б».

    Живая речь повторяется сама (скандирование на стриме, выкрики), и то же
    делает зациклившийся распознаватель. В плашку это уезжало как есть:
    «ПОБЕДА НА ТУРНИРЕ ПОБЕДА НА ТУРНИРЕ ПОБЕДА НА ТУРНИРЕ ПОБЕДА» —
    и в кадре, и в имени файла.

    Убираем повтор любой длины, а не только одно слово подряд: беда именно
    в блоках. Сравниваем без регистра — «Победа» и «ПОБЕДА» здесь одно и то же.
    """
    words = text.split()
    kept = []
    place = 0
    # Размер блока, схлопнутого на прошлом шаге. Нужен для оборванного хвоста
    # в самом конце — но только там, где повтор уже случился (см. ниже).
    collapsed = 0

    while place < len(words):
        skipped = False
        # Длинные блоки проверяем первыми: иначе «А Б А Б» схлопнется по
        # одному слову и оставит хвост.
        for size in range(min(most, len(kept)), 0, -1):
            here = [w.lower() for w in words[place:place + size]]
            before = [w.lower() for w in kept[-size:]]
            if len(here) == size and here == before:
                place += size
                collapsed = size
                skipped = True
                break

        # Оборванный повтор в самом конце: «А Б А Б А» оставляла хвост «А»,
        # и в плашке висело «ПОБЕДА НА ТУРНИРЕ ПОБЕДА». Хвост режем только
        # если блок перед ним и правда повторялся: без этой оговорки правило
        # отъедало законное последнее слово у «я хочу сказать что я».
        if not skipped and collapsed:
            tail = [w.lower() for w in words[place:]]
            head = [w.lower() for w in kept[-collapsed:]]
            if tail and len(tail) < collapsed and head[:len(tail)] == tail:
                break

        if not skipped:
            kept.append(words[place])
            place += 1
            collapsed = 0

    return " ".join(kept)


def _tidy(piece):
    """Убирает зачин, запинки живой речи и повторы."""
    piece = undouble(_STUTTER.sub(r"\1", re.sub(r"\s+", " ", piece)).strip())
    while True:
        shorter = _FILLER.sub("", piece, count=1).strip()
        if shorter == piece:
            return piece[:1].upper() + piece[1:] if piece else piece
        piece = shorter


# Слова, на которых надпись кончаться не может. Обрубок «…и выгружает их
# при» читается как сбой программы: слово целое, а мысль оборвана. Режем
# такие хвосты, даже если надпись станет короче задуманного.
_TAIL_JUNK = frozenset("""
и а но или да что чтобы как когда где куда пока при в во на с со к ко из
от до для по за над под про без у о об обо между через если то же ли бы
не ни его её ее их им ими ему ей это этот эта эти тот та те
""".split())


# Слова, перед которыми фразу можно оборвать без потери смысла: то, что
# идёт за ними, — уже второе утверждение. «Плагин собирает данные оффлайн»
# читается законченно, «…и выгружает» — нет.
_JOINTS = ("и", "а", "но", "или", "чтобы", "потому", "поэтому", "если",
           "когда", "пока", "хотя", "зато", "причём", "при", "с", "без")


def _drop_tail(text):
    """Убирает служебные слова с конца надписи."""
    words = text.split()
    while words and words[-1].lower().strip(".,;:—-»)") in _TAIL_JUNK:
        words.pop()
    return " ".join(words).rstrip(" ,;:—-")


def _at_joint(head, least):
    """Обрыв перед союзом: первый, после которого фраза уже стоит на ногах.

    Резать по последнему союзу нельзя — получится «собирает данные оффлайн
    и выгружает их», то есть снова половина мысли. Берём первый, который
    оставляет достаточно текста.
    """
    words = head.split()
    for index in range(1, len(words)):
        if words[index].lower() not in _JOINTS:
            continue
        piece = " ".join(words[:index]).rstrip(" ,;:—-")
        if len(piece) >= least:
            return piece
    return ""


def hook(title, limit=HOOK_LIMIT):
    """Заголовок главы в виде надписи для кадра: короче и без хвостов.

    Когда фраза не влезает, режем по границе оборота — по запятой или тире, —
    и тогда надпись читается как законченная: «Ты сказал, что там есть
    векторная бд». Резать по буквам нельзя: получается «что там с помощ…»,
    и это выглядит как сбой программы, а не как заголовок.

    Многоточия в конце тоже нет. Оно честно говорит «здесь оборвано», но
    зрителю от этой честности ни тепло ни холодно: надпись должна читаться
    как готовая фраза, поэтому лучше отрезать лишнее слово.
    """
    text = _drop_tail(undouble(re.sub(r"\s+", " ", title).strip(" .•—-")))
    if len(text) <= limit:
        return text

    head = text[:limit]

    # Граница оборота: после неё мысль уже стоит на ногах.
    clause = max(head.rfind(mark) for mark in (",", ";", ":", " —", " -"))
    if clause >= limit // 2:
        return _drop_tail(head[:clause])

    # Знаков препинания нет — ищем союз: за ним начинается вторая мысль,
    # и оборвать перед ним честнее, чем посреди первой.
    joint = _at_joint(head, limit // 2)
    if joint:
        return _drop_tail(joint)

    # Не нашлось и его — обрываем хотя бы по целому слову.
    space = head.rfind(" ")
    cut = head[:space] if space >= limit // 2 else head[: limit - 1]
    return _drop_tail(cut)
