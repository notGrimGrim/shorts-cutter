# Кэш на процесс: несколько pairs подряд по одному ролику не должны каждый
# раз заново спрашивать дату публикации.
_AGE_CACHE = {}


def _video_age_years(source, on_note=None):
    """Возраст ролика в годах по дате публикации, или None, если не узнать.

    download.probe() (её контракт не меняю — файл вне зоны) не отдаёт дату
    в своём словаре, хотя yt-dlp её знает. Спрашиваем сами, отдельным
    лёгким запросом без обходной лестницы download._ladder: если основной
    прогон уже достал по этой ссылке метаданные (probe вызывается раньше
    в pairs.plan → cut.py), сеть скорее всего доступна и простому запросу.
    Не вышло — не выдумываем: None, и вызывающий не проверяет привязку ко
    времени вовсе (см. _age_bucket).
    """
    if not source or source in _AGE_CACHE:
        return _AGE_CACHE.get(source)
    if not str(source).strip().lower().startswith(("http://", "https://", "www.")):
        _AGE_CACHE[source] = None
        return None

    try:
        import yt_dlp
        with yt_dlp.YoutubeDL({
            "quiet": True, "no_warnings": True, "skip_download": True,
            "socket_timeout": 20,
        }) as ydl:
            info = ydl.extract_info(source, download=False)
        raw = info.get("upload_date") or info.get("release_date")
        if not raw:
            raise ValueError("yt-dlp не отдал upload_date/release_date")
        published = datetime.strptime(str(raw), "%Y%m%d")
        years = (datetime.now() - published).days / 365.25
    except Exception as error:
        if on_note:
            on_note(f"дату публикации узнать не вышло ({error}) — "
                    f"привязку ко времени не проверяю")
        _AGE_CACHE[source] = None
        return None

    _AGE_CACHE[source] = years
    return years


# ── разнос перекрывающихся окон (задание 2, механизм 1) ────────────────────

def _overlap(a, b):
    """Доля пересечения двух окон от длины короткого из них. 0..1."""
    inter = min(a.end, b.end) - max(a.start, b.start)
    if inter <= 0:
        return 0.0
    shortest = min(a.end - a.start, b.end - b.start)
    return inter / shortest if shortest > 0 else 1.0


def _diversify(pairs_list, span=WINDOW_SPAN, cap=WINDOW_CAP, overlap=NMS_OVERLAP):
    """Гасит дубли и не даёт одному отрезку ролика забрать весь шортлист.

    Кандидаты уже отсортированы pairs.rate() по своему счёту. Идём жадно:
    берём кандидата, если он не перекрывается больше чем на `overlap` ни с
    одним уже взятым (иначе это то же место разговора, просто с другим
    краем — не другая тема) и в его WINDOW_SPAN-отрезке ролика ещё есть
    место (не больше `cap`, кто бы ни просил сверху в count).

    Это и есть долг, оставленный Этапом 7 («pairs.build() без NMS отдаёт
    плотные перекрывающиеся окна... нужно решение координатора: NMS в
    pairs.rate()/plan() или отбор перекрытий в think.select()») — закрыт
    здесь: без этого шага rank() на длинной главе (WysbVnaswgo, «Что
    дальше», 62 окна подряд) видит почти одни её копии и не успевает
    добраться до остальных тем ролика. Легитимные ч.1/ч.2 длинной темы
    почти не перекрываются между собой (это разные куски разговора, не
    варианты одного среза) и оба обычно переживают этот шаг; свести их
    вместе, если конкуренция за place в бюджете разведёт по времени
    слишком сильно — не работа этого шага, это дальше решает судья и
    _drop_chained (задание 2, механизм 2).
    """
    kept = []
    per_span = {}
    for pair in pairs_list:
        bucket = int(pair.start // span)
        if per_span.get(bucket, 0) >= cap:
            continue
        if any(_overlap(pair, other) > overlap for other in kept):
            continue
        per_span[bucket] = per_span.get(bucket, 0) + 1
        kept.append(pair)
    return kept


# ── точечная обрезка рекламы (задание 4) ────────────────────────────────────

def _norm_tokens(text):
    return re.findall(r"[a-zа-яё0-9]+", (text or "").lower())


def _locate_phrase(words, lo, hi, phrase):
    """(начало, конец) дословной фразы внутри [lo, hi) секунд ролика, или None.

    Ищем как подряд идущие нормализованные токены среди слов расшифровки.
    Не нашли — None: раз судья процитировал не то, что реально сказано,
    врать себе про место реза хуже, чем не резать вовсе.
    """
    target = _norm_tokens(phrase)[:6]
    if not target or not words:
        return None
    pool = [w for w in words if lo - 0.01 <= w.start < hi]
    tokens, owner = [], []
    for index, word in enumerate(pool):
        for token in _norm_tokens(word.text):
            tokens.append(token)
            owner.append(index)
    n = len(target)
    for start in range(len(tokens) - n + 1):
        if tokens[start:start + n] == target:
            first, last = pool[owner[start]], pool[owner[start + n - 1]]
            return first.start, last.end
    return None


def _locate_in_text(text, lo, hi, phrase, edge):
    """То же самое по доле символов в pair.text — когда слов с таймкодами нет.

    Грубее: предполагает ровный темп речи внутри окна. Рабочий путь только
    когда судью зовут без `words` — так сейчас происходит в проде, см.
    WORKLOG про интеграционный долг (pairs.plan() их не передаёт).
    """
    target = _norm_tokens(phrase)[:4]
    tokens = _norm_tokens(text)
    if not target or not tokens:
        return None
    n = len(target)
    for index in range(len(tokens) - n + 1):
        if tokens[index:index + n] == target:
            edge_index = index if edge == "start" else index + n
            return lo + (edge_index / len(tokens)) * (hi - lo)
    return None


def _snap_cut(words, lo, hi, at, edge):
    """Ближайшая настоящая граница предложения, не теряющая нужный край.

    «start» — начало предложения, содержащее или предшествующее `at` (не
    отрезать первые слова keep_from); «end» — конец предложения, содержащий
    `at` целиком (не отрезать последние слова keep_to). Тот же приём, что
    pairs._fit_end использует для своих окон: настоящая граница фразы, а
    не случайная пауза. Подходящей границы рядом нет — оставляем `at` как
    есть, без выдумки.
    """
    if not words:
        return at
    lines = pairs.sentences(words)
    if edge == "start":
        before = [s.start for s in lines if lo - 0.5 <= s.start <= at + 0.05]
        return max(before) if before else at
    after = [s.end for s in lines if at - 0.05 <= s.end <= hi + 0.5]
    return min(after) if after else at


# Тот же самый признак рекламы, которым pairs.rate() штрафует свой счёт
# (pairs._JUNK) — переиспользуем как код-проверку judge(): слабая модель
# на живом прогоне (WysbVnaswgo, CdcVjxzcmwc) иногда предлагала
# keep_from/keep_to без всякой рекламы в вырезаемом куске вообще (`why`
# при этом даже не про рекламу — модель просто решила укоротить кусок).
# Доверять этому нельзя: обрезаем только то, что реально похоже на
# рекламу/подписку, а не то, что модель сочла лишним.
#
# Расширение задания 4 этой сессии: pairs._JUNK ловит «канал»/«подпис»/
# «реклам», но не сам призыв в Telegram, если текст не использует эти
# слова буквально — живой случай, ушедший в прод необрезанным:
# rLkg_9Muqhc, seg_39_136.ass (133.3–137.2с внутри окна), «А ещё
# приглашаю тебя вступить в мой закрытый клуб в Телеграме» — ни «канал»,
# ни «подпис», ни «реклам» в этих словах нет, только «Телеграм». Это
# пробел в словаре, не предел точности модели (WORKLOG про ~1/10 успеха
# на Groq в трудном случае «реклама в середине» — здесь другой случай,
# реклама в хвосте окна, простой для модели, но её верный keep_to всё
# равно отклонила бы эта же проверка). Добавлено отдельным «|телеграм»
# здесь, а не правкой pairs._JUNK: там это слово задело бы pairs.rate()
# по ВСЕМУ тексту окна — единственный найденный на всех известных
# роликах пример, где «телеграм» не реклама (cWIgmXxB51o, «мы с вами
# переписывались в Инстаграме и в Телеграме» — реплика в начале
# интервью), в pairs.rate() обрушил бы счёт целому окну ни за что; здесь
# же слово участвует только в проверке уже предложенного судьёй среза —
# риск на порядок уже.
_AD_SIGNAL = re.compile(pairs._JUNK.pattern + r"|телеграм", re.IGNORECASE)


def _cut_text(pair, words, lo, hi):
    """Текст вырезаемого куска [lo, hi) — по словам, если есть, иначе по доле pair.text."""
    if words:
        return " ".join(w.text for w in words if lo - 0.01 <= w.start < hi)
    if not pair.duration:
        return ""
    frac_lo = max(0.0, (lo - pair.start) / pair.duration)
    frac_hi = min(1.0, (hi - pair.start) / pair.duration)
    text = pair.text
    return text[int(frac_lo * len(text)):int(frac_hi * len(text))]


def _resolve_trim(pair, keep_from, keep_to, words, second_topic=False):
    """keep_from/keep_to судьи → новые границы окна. Не мутирует pair.

    Возвращает (start, end, заметки для лога, viable). viable=False значит
    «после обрезки почти ничего не остаётся» — AD_MIN_KEEP/AD_MIN_FRACTION,
    те же числа для всех роликов, а не самооценка модели (задание 2: порог
    по калибровке модели в код не возвращаем, даже здесь).

    second_topic — задание 1 этой сессии: keep_to может резать не рекламу,
    а конец первой из нескольких тем, заглотнутых одним окном (см.
    WORKLOG.md, Этап 15, Дефект 2.2 — коридор 25–105с почти всегда вмещает
    несколько законченных тем на плотном материале, и _fit_end по design
    берёт самый дальний конец). У «конца темы» нет словаря вроде
    _AD_SIGNAL: это ровно тот случай, для которого в проекте и зовут
    модель, а не арифметику (см. докстринг модуля). Поэтому для keep_to с
    second_topic=True код-гейт по _AD_SIGNAL не применяется — вместо него
    работает та же защита от галлюцинации, что и всегда для этого поля:
    фраза обязана найтись дословно в речи (_locate_phrase/_locate_in_text),
    иначе at остаётся None и резать нечем. keep_from второй-темой не
    прикрывается нигде — по заданию сигнал только про keep_to.
    """
    start, end = pair.start, pair.end
    notes = []

    if keep_from:
        match = _locate_phrase(words, pair.start, pair.end, keep_from) if words else None
        at = match[0] if match else (
            None if words else _locate_in_text(pair.text, pair.start, pair.end, keep_from, "start")
        )
        if at is None:
            notes.append(f"не нашла начало «{keep_from}» — не режу")
        elif not _AD_SIGNAL.search(_cut_text(pair, words, pair.start, at)):
            notes.append("в вырезаемом начале нет слов рекламы/подписки — не режу")
        else:
            start = _snap_cut(words, pair.start, pair.end, at, "start")
            notes.append(f"начало {pair.start:.1f}→{start:.1f}с")

    if keep_to:
        match = _locate_phrase(words, pair.start, pair.end, keep_to) if words else None
        at = match[1] if match else (
            None if words else _locate_in_text(pair.text, pair.start, pair.end, keep_to, "end")
        )
        if at is None:
            notes.append(f"не нашла конец «{keep_to}» — не режу")
        elif not second_topic and not _AD_SIGNAL.search(_cut_text(pair, words, at, pair.end)):
            notes.append("в вырезаемом конце нет слов рекламы/подписки — не режу")
        else:
            end = _snap_cut(words, pair.start, pair.end, at, "end")
            notes.append(f"конец {pair.end:.1f}→{end:.1f}с")

    if end <= start:
        return pair.start, pair.end, notes, True

    kept = end - start
    if kept < AD_MIN_KEEP or kept < AD_MIN_FRACTION * pair.duration:
        return pair.start, pair.end, notes, False

    return start, end, notes, True


# ── судья: разбор ответа (задания 1 и 4) ────────────────────────────────────

def _as_grade(value):
    text = str(value or "").strip().strip(".!").lower()
    if text in ("да", "true", "yes", "y", "1", "ok", "ок", "годен", "годится"):
        return "да"
    if text in ("с натяжкой", "натяжка", "натяжкой", "почти", "weak", "partial",
                "с оговоркой", "условно", "скорее да"):
        return "с натяжкой"
    if text in ("нет", "false", "no", "n", "0", "не годен", "не годится", "брак"):
        return "нет"
    return None


def _as_bool(value, default=True):
    if isinstance(value, bool):
        return value
    text = str(value or "").strip().lower()
    if text in ("нет", "false", "no", "n", "0"):
        return False
    if text in ("да", "true", "yes", "y", "1"):
        return True
    return default


def _judge_prompt(pair, age_bucket, age_years, authored_hook=False):
    if pair.chapter:
        hook_note = _JUDGE_CHAPTER_NOTE
    elif authored_hook:
        hook_note = _JUDGE_AUTHORED_NOTE
    else:
        hook_note = ""

    age_note = ""
    if age_bucket in ("old", "mid"):
        template = _JUDGE_AGE_OLD if age_bucket == "old" else _JUDGE_AGE_MID
        age_note = template.format(years=age_years)
        found = _years_mentioned(f"{pair.hook} {pair.text}")
        if found:
            age_note += f"В самом тексте встречаются числа: {', '.join(found)}.\n"

    return _JUDGE.format(
        title=pair.hook or "без надписи",
        text=re.sub(r"\s+", " ", pair.text)[:JUDGE_TEXT],
        limit=TITLE_LIMIT,
        hook_note=hook_note,
        age_note=age_note,
    )


def judge(pair, on_note=None, age_bucket=None, age_years=None, words=None,
          authored=frozenset()):
    """Второй проход: отдельная роль, отдельный промпт — судья, не искатель.

    Возвращает "да" / "с натяжкой" / "нет". None — спросить не удалось
    (сеть, квота, кривой ответ): это не значит «нет», значит «не судили»,
    и такой момент в select() остаётся как есть, без штрафа и без права
    на исключение из разноса по времени (см. _drop_chained: confirmed —
    только прямое «да»).

    words — слова расшифровки с таймкодами, нужны для точной обрезки
    рекламы и смены темы (см. _resolve_trim/_snap_cut). Без них резать
    можно только по доле текста — грубее, но не отказываемся вовсе.

    authored — см. rank(): (start, end) пар с хуком из вопроса ведущего.
    Как и заголовок главы, дословно не переписываем без причины — но обе
    причины на это (задания 2 и 3 этой сессии: не хватает контекста без
    видео, и отдельно — многословность) теперь общие для обоих источников
    хука, не только для главы, см. ветку pair.chapter or is_authored ниже.
    """
    is_authored = (round(pair.start, 2), round(pair.end, 2)) in authored
    meter = _Meter(on_note)
    prompt = _judge_prompt(pair, age_bucket, age_years, is_authored)

    answer = _ask_any(prompt, meter, JUDGE_TOKENS, on_note)
    if not answer:
        return None

    readable = _as_bool(answer.get("readable"), default=True)
    grade = _as_grade(answer.get("ok"))
    why = str(answer.get("why") or "").strip()

    if grade is None:
        return None

    if not readable:
        if on_note:
            on_note(f"  отвела «{pair.hook}»: речь не читается"
                    f"{' — ' + why if why else ''}")
        return "нет"

    if grade == "нет":
        if on_note:
            on_note(f"  отвела «{pair.hook}»: {why or 'нечего пересказать'}")
        return "нет"

    if pair.chapter or is_authored:
        # Глава и вопрос ведущего — оба чужой, уже готовый текст, дословно
        # неприкосновенный по умолчанию (глава — решение Рината с начала
        # проекта, см. rank(); вопрос ведущего — задание 3 Этапа 9,
        # «предпочесть его сочинённому»). Но оба написаны в расчёте на
        # контекст всего видео, которого у зрителя шортса нет — раньше
        # (Этап 11) эту проверку (hook_ok, тогда chapter_ok) проходила
        # только глава, задание 2 этой сессии расширяет её на вопрос
        # ведущего тем же правом на два пути (дописать тему или переписать
        # целиком). tight (задание 3) — независимая от hook_ok причина той
        # же правки: заголовок может быть верным, самодостаточным и всё
        # равно многословным («И раз уж мы упомянули MDMA, помогает ли он
        # от депрессии?» — оба «да», а надпись всё равно раздута). Не
        # смогла разобрать ответ — default=True на оба: не трогаем, тот же
        # приоритет по умолчанию, что был у chapter_ok.
        kind = "глава" if pair.chapter else "вопрос ведущего"
        hook_ok = _as_bool(answer.get("hook_ok"), default=True)
        tight = _as_bool(answer.get("tight"), default=True)
        if hook_ok and tight:
            if on_note:
                on_note(f"  надпись не менялась ({kind}: самодостаточно): {pair.hook}")
        else:
            before = pair.hook
            # source — то же окно текста, что видел судья в промпте
            # (_judge_prompt режет по JUDGE_TEXT, не по 300 знаков): сверка
            # по более узкому окну браковала как «не в тему» собственный
            # верный ответ судьи, если тема встречалась дальше начала —
            # живой пример поймала на «С чего начать, если ты забыл?».
            pair.hook = _clean_title(answer.get("title"), pair.hook,
                                      pair.text[:JUDGE_TEXT])
            reason = "не хватает контекста без видео" if not hook_ok else "многословна"
            if on_note:
                on_note(f"  поправила надпись ({kind}, {reason}): "
                        f"«{before}» → «{pair.hook}»")
    else:
        pair.hook = _clean_title(answer.get("title"), pair.hook,
                                  pair.text[:JUDGE_TEXT])

    keep_from = str(answer.get("keep_from") or "").strip()
    keep_to = str(answer.get("keep_to") or "").strip()
    if keep_from or keep_to:
        # second_topic (задание 1 этой сессии) — keep_to не только про
        # рекламу: см. _resolve_trim и WORKLOG, Этап 15, Дефект 2.2.
        second_topic = _as_bool(answer.get("second_topic"), default=False)
        new_start, new_end, notes, viable = _resolve_trim(
            pair, keep_from, keep_to, words, second_topic)
        if not viable:
            if on_note:
                on_note(f"  отвела «{pair.hook}»: после обрезки почти "
                        f"ничего не остаётся")
            return "нет"
        if (new_start, new_end) != (pair.start, pair.end):
            pair.start, pair.end = new_start, new_end
            if on_note:
                what = "лишнюю тему" if second_topic else "рекламу"
                on_note(f"  обрезала {what} в «{pair.hook}»: {'; '.join(notes)}")
        elif notes and on_note:
            on_note(f"  правку в «{pair.hook}» не применила: {'; '.join(notes)}")

    if grade == "с натяжкой":
        pair.score = round(pair.score * WEAK_PENALTY, 3)
        if on_note:
            on_note(f"  с натяжкой «{pair.hook}»: {why or 'заход или конец шероховаты'}")

    return grade


# ── разнос по времени (задание 2, механизм 2) ───────────────────────────────

def _drop_chained(items, min_gap=MIN_GAP, chain_gap=CHAIN_GAP, standalone=()):
    """Свернуть цепочки подряд идущих окон: (что осталось, сколько выброшено).

    Если между концом одного момента и началом следующего прошло меньше
    min_gap секунд разговора — это один и тот же кусок беседы, разрезанный
    на части, и остаётся из него один, сильнейший по score.

    Исключение: пара НЕ сворачивается, если judge() независимо подтвердил
    «да» по каждому из двух моментов (standalone — их (start, end)) И
    разрыв не меньше chain_gap. Это прямое требование Рината: части одной
    длинной темы (ч.1, ч.2…) не должны пропасть только потому, что идут
    подряд, — но арифметика по одному лишь времени не отличит настоящую
    вторую часть от куска, на который разговор просто продолжился без
    новой мысли, поэтому исключение работает только когда судья прочитал
    оба куска по отдельности и оба счёл самостоятельными.
    """
    approved = set(standalone)
    ordered = sorted(items, key=lambda pair: pair.start)
    kept = []
    dropped = 0
    for pair in ordered:
        if kept:
            gap = pair.start - kept[-1].end
            both_confirmed = (
                (pair.start, pair.end) in approved
                and (kept[-1].start, kept[-1].end) in approved
            )
            chained = gap < min_gap and not (gap >= chain_gap and both_confirmed)
            if chained:
                dropped += 1
                if pair.score > kept[-1].score:
                    kept[-1] = pair
                continue
        kept.append(pair)
    return kept, dropped


# ── добор из отсеянного _diversify() (задание этой сессии) ─────────────────

def _topup(survivors, count, note, excluded, floor, age_bucket, age_years,
           words, authored, standalone):
    """После судьи не хватило count — досудить то, что `_diversify()` отсеяла.

    `_diversify()` режет пул до судьи по перекрытию с уже взятым или по
    потолку кандидатов на отрезок ролика (WINDOW_CAP на WINDOW_SPAN) — это
    конкуренция за место, а не оценка качества. `excluded` — то, что она
    выбросила и что judge() поэтому ни разу не видел; не путать с pool-
    кандидатами, которым уже сказали «нет» в основном проходе, — тех сюда
    не возвращаем (задание прямо разделяет два случая).

    excluded уже отсортирован pairs.rate() по убыванию — тем же порядком,
    что был у pairs_list на входе в select(). floor — сырой счёт худшего из
    оставшихся в pool после _diversify(), посчитанный ДО того, как rank()/
    judge() переписали кому-то score своей, несравнимой шкалой; кандидатов
    ниже floor в добор не берём — раз _diversify пропустила что-то с таким
    счётом, это и есть планка приемлемого, а не произвольное число, и не
    подгонка слабым (Этап 9).

    Бюджет — TOPUP_BUDGET_MULT * count кандидатов на судью, не весь ролик
    заново: не хватило и этого — тема ролика узкая по существу.
    """
    candidates = [p for p in excluded if p.score > floor]
    if not candidates:
        return survivors

    candidates = candidates[:count * TOPUP_BUDGET_MULT]
    note(f"досуживаю {len(candidates)} кандидатов, отсеянных _diversify() "
         f"(сырой счёт выше {floor:.2f})")

    for pair in candidates:
        try:
            grade = judge(pair, note, age_bucket, age_years, words, authored)
        except _Stop as stop:
            note(f"судья не отвечает при доборе ({stop}) — беру, что есть")
            break
        if grade is None or grade == "нет":
            continue
        if grade == "да":
            standalone.add((pair.start, pair.end))
        survivors.append(pair)

    return survivors


# ── то, ради чего всё ────────────────────────────────────────────────────

def _finish(items, count, note, standalone=()):
    """Разнос по времени и честный срез по count — общий хвост всех путей."""
    spaced, dropped = _drop_chained(items, MIN_GAP, CHAIN_GAP, standalone)
    if dropped:
        note(f"свёрнуто подряд идущих окон: {dropped} — это нарезка "
             f"разговора, а не отбор")
    spaced.sort(key=lambda pair: (-pair.score, pair.start))
    result = spaced[:count]
    if len(result) < count:
        note(f"нашлось {len(result)} из запрошенных {count} моментов")
    return result


def select(pairs_list, video_title="", count=3, on_note=None, words=None, source=""):
    """Что пойдёт в нарезку.

    Порядок: 1) не больше WINDOW_CAP окон на WINDOW_SPAN секунд ролика и не
    больше NMS_OVERLAP перекрытия с уже взятым — иначе длинная глава
    (WysbVnaswgo, «Что дальше», 62 окна подряд) топит и модель, и любой
    отбор в почти одинаковых кандидатах; 2) rank() сравнивает хуки между
    собой; 3) judge() проверяет каждый отдельно — да/с натяжкой/нет,
    читаемость, враньё плашки, точечная обрезка рекламы, привязка ко
    времени; 4) _drop_chained — разнос по времени, кроме подтверждённой
    судьёй пары ч.1/ч.2; 5) count — потолок, не цель: меньше, чем просили,
    — сказать прямо, не добирать слабым (это и есть прямой почин жалобы
    Рината на «Как войти в айти в 25 году» — тот клип попал в подборку
    только потому, что тройку было нечем больше заполнить; здесь такого
    заполнения в коде больше нет); 6) не хватило count даже так — прежде
    чем сдаваться, _topup() досуживает то, что _diversify() отсеяла на
    шаге 1 по перекрытию/потолку, а не по качеству (см. её докстринг);
    это расширение пула поиска, не понижение планки — добор всё равно
    идёт через judge() и порог по сырому счёту, слабым не подгоняем.

    words и source — необязательные. Без words обрезка рекламы работает
    только грубой прикидкой по доле текста (см. _resolve_trim). Без source
    привязку ко времени не проверяем вовсе — не выдумываем дату публикации.
    Единственный вызывающий сейчас, pairs.plan(), их не передаёт (см.
    WORKLOG.md, интеграционный долг: файл вне зоны этой сессии). Тестовый
    прогон передаёт оба явно.
    """
    note = on_note or (lambda text: None)
    if not pairs_list:
        return []

    pool = _diversify(pairs_list)
    note(f"кандидатов после разноса перекрытий и потолка {WINDOW_CAP} на "
         f"{WINDOW_SPAN / 60:.0f} мин: {len(pool)} из {len(pairs_list)}")

    # Для _topup(), если после судьи не хватит count: то, что _diversify()
    # отсеяла, и планка сырого счёта — оба берутся здесь, ДО того, как
    # rank()/judge() начнут переписывать pool своей, несравнимой шкалой
    # score (см. _topup).
    excluded = [p for p in pairs_list if p not in pool]
    floor = min((p.score for p in pool), default=0.0)

    # Хук уже пришёл от pairs.py (вопрос ведущего) — авторский текст, как и
    # заголовок главы (задание 3): фиксируем набор ДО того, как rank()/judge()
    # получат право его переписать. От pairs_list, не только pool, — чтобы
    # то же право досталось и кандидатам, которых добавит _topup().
    authored = {
        (round(p.start, 2), round(p.end, 2))
        for p in pairs_list if not p.chapter and p.hook
    }

    if not anyone():
        note("модели нет — отбираю своим счётом")
        return _finish(pool, count, note)

    age_years = _video_age_years(source, note)
    age_bucket = _age_bucket(age_years)

    shortlist = rank(pool, video_title, count + RANK_BUFFER, note, authored)
    if not shortlist:
        return _finish(pool, count, note)

    queue = list(shortlist)
    spare = [p for p in pool if p not in shortlist]
    survivors = []
    standalone = set()
    budget = max(count * JUDGE_BUDGET_MULT, len(shortlist))
    judged = 0
    dead = False

    while queue and judged < budget:
        pair = queue.pop(0)
        if dead:
            survivors.append(pair)
            continue
        judged += 1
        try:
            grade = judge(pair, note, age_bucket, age_years, words, authored)
        except _Stop as stop:
            note(f"судья не отвечает ({stop}) — дальше беру кандидатов как есть")
            dead = True
            survivors.append(pair)
            continue
        if grade is None:
            survivors.append(pair)
            continue
        if grade == "нет":
            if spare:
                queue.append(spare.pop(0))
            continue
        if grade == "да":
            standalone.add((pair.start, pair.end))
        survivors.append(pair)

    result = _finish(survivors, count, note, standalone)
    if len(result) < count and not dead and excluded:
        survivors = _topup(survivors, count, note, excluded, floor,
                            age_bucket, age_years, words, authored, standalone)
        result = _finish(survivors, count, note, standalone)
    return result
