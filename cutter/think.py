def _number(value, low, high):
    try:
        number = int(value)
    except (TypeError, ValueError):
        return None
    return number if low <= number <= high else None


def _clean_title(text, fallback="", source=""):
    """Надпись в кадр: без кавычек, без точки, законченной фразой.

    Обрезкой занимается chapters.hook — там она уже сделана правильно: по
    границе оборота и без служебного хвоста. Держать вторую такую же логику
    здесь значит однажды поправить одну и забыть другую.

    Мусор от слабой модели (обрывок промпта/JSON-схемы, реплика без темы,
    надпись не по теме куска) отбраковываем здесь, в коде: промпт можно
    попросить не делать так, но переспросить модель нечем — это последний
    рубеж перед кадром. source — вопрос и начало ответа этого куска; пусто,
    если сверять не с чем (например, в юнит-тестах).
    """
    from . import chapters  # локально: think нужен и без разбора глав

    text = re.sub(r"\s+", " ", str(text or "")).strip().strip('"«»').rstrip(".")
    if not text or _looks_like_junk(text):
        return fallback
    if source and _looks_off_topic(text, source):
        return fallback
    return chapters.hook(text, TITLE_LIMIT)


# Слова из текста самих промптов — если ответ модели целиком состоит из них,
# это не надпись, а протёкший обрывок инструкции или JSON-схемы (живой пример
# с qwen2.5: "Надпись — точнее" — это кусок описания поля title из _JUDGE).
# «...»-примеры (готовые надписи для иллюстрации, не сама инструкция) из этого
# счёта исключены: живой пример на живом прогоне (задание 3, дополнение с
# самодостаточностью главы) — модель Groq дала для «С чего начать, если ты
# забыл?» ровно тот же текст, что и пример в chapter_note («С чего начать
# изучение математики, если ты забыл?» — тот самый пример из подсказки), и
# без этого исключения правильный ответ браковался как «протёкший пример».
_PROMPT_WORDS = frozenset(
    w for w in re.findall(
        r"[a-zа-яё]+",
        re.sub(
            r"«[^»]*»", " ",
            _RANK + " " + _JUDGE + " " + _JUDGE_CHAPTER_NOTE + " "
            + _JUDGE_AUTHORED_NOTE + " " + _JUDGE_AGE_OLD + " " + _JUDGE_AGE_MID,
        ).lower(),
    )
    if len(w) > 2
)

# Служебные слова без темы — надпись из одних них не хук, а обрывок реплики
# («да, есть такая возможность»): она не называет предмет и не даёт повода
# смотреть дальше.
_FILLER = frozenset("""
да нет есть был была было были ну вот же ли бы то это этот эта эти
там тут такой такая такое такие тот та те он она они себя свой своя
своё свои конечно наверное кажется просто действительно точно правда
всё все возможность вопрос тема дело история ситуация случай момент
факт суть штука вещь способ вариант
""".split())


def _looks_like_junk(title):
    """Надпись без темы: обрывок промпта/схемы, чужой язык или обрывок реплики.

    Три случая различаем по-разному: иероглифы (кириллица/латиница в промпте
    не даёт модели повода на них перейти — раз они есть, ответ сбоил) —
    сразу мусор; если все содержательные слова (длиннее двух букв) совпадают
    со словами из текста самих промптов — протекла инструкция; если все
    входят в список служебных — это не хук, а связка без предмета. Настоящий
    хук называет тему, и хотя бы одно её слово в оба словаря не попадёт.
    """
    if re.search(r"[一-鿿぀-ヿ가-힯]", title):
        return True
    words = [w for w in re.findall(r"[a-zа-яё]+", title.lower()) if len(w) > 2]
    if not words:
        return True
    if all(w in _PROMPT_WORDS for w in words):
        return True
    if all(w in _FILLER for w in words):
        return True
    return False


# Служебные слова и местоимения — не тема, а грамматический клей. Отдельно от
# _FILLER: там генерик-слова вроде «возможность», тут только то, что не может
# быть содержанием само по себе ни в каком контексте.
_STOP = frozenset("""
что как для про при над под без если чтобы когда куда откуда почему
потому который которая которое которые какой какая какое какие сколько
чем чему кто себя себе свою свой всё все весь вся эти этот эта того тому
этому этого этой этим тем там тут здесь туда сюда оттуда затем потом
теперь пока после между через среди около возле перед именно только
тоже также даже ещё просто очень совсем прямо ведь либо или иначе есть
было были будет будут стал стала стало стали может можно нужно надо
нельзя раз будто хотя пусть лишь чуть более менее самим самой самого
самих него нее них ними нём ней ним чей чья чье чьи мои твои наши ваши
""".split())


def _significant(text):
    """Содержательные слова текста: длиннее двух букв, не служебные."""
    words = re.findall(r"[a-zа-яё]+", text.lower())
    return {w for w in words if len(w) > 2 and w not in _STOP}


def _looks_off_topic(title, source):
    """Надпись не пересекается по смыслу со своим куском — взялась не о нём.

    source — вопрос и начало ответа этого куска. Если у надписи и источника
    нет ни одного общего значимого слова, надпись не называет тему куска:
    либо модель перепутала пару, либо сочинила заголовок из ничего.
    """
    title_words = _significant(title)
    if not title_words:
        return True
    return title_words.isdisjoint(_significant(source))


def _rank_lines(pairs_list):
    """Список хуков для модели: номер, длина ответа и его начало."""
    rows = []
    for number, pair in enumerate(pairs_list, 1):
        opening = re.sub(r"\s+", " ", pair.text)[:110]
        rows.append(
            f"[{number}] ({pair.duration:.0f}с) {pair.hook}\n"
            f"     ответ: {opening}…"
        )
    return "\n".join(rows)


def rank(pairs_list, video_title="", count=3, on_note=None, authored=frozenset()):
    """Отбирает лучшие пары одним запросом — модель сравнивает хуки между собой.

    Возвращает выбранные пары с надписью от модели. Не смогла ответить —
    возвращаем пустой список, и вызывающий берёт свой счёт: тут нет ничего,
    что стоило бы выдумывать наугад.

    authored — (start, end) пар, чей hook уже пришёл из pairs.py (вопрос
    ведущего, не пустая строка). Такой текст — тоже авторский, как и
    заголовок главы: задание 3 прямо просит предпочесть его сочинённому,
    поэтому здесь его не даём переписывать, тем же приёмом, что и chapter.
    """
    if not pairs_list:
        return []

    shown = list(pairs_list)[:RANK_LIMIT]
    meter = _Meter(on_note)
    prompt = _RANK.format(
        video=video_title or "интервью",
        count=count,
        lines=_rank_lines(shown),
    )

    try:
        answer = _ask_any(prompt, meter, RANK_TOKENS, on_note)
    except _Stop as stop:
        if on_note:
            on_note(f"модель не отвечает ({stop}) — отбираю своим счётом")
        return []

    # Молчание модели — не тот случай, что короткий список: она честно не
    # смогла ответить, и достраивать этот ответ своим счётом было бы враньём
    # от её имени. А вот "picked" короче count — это ответ, который есть, и
    # его можно дотянуть.
    if answer is None:
        return []

    picked = answer.get("picked") or []
    if not isinstance(picked, list):
        return []

    chosen = []
    for row in picked[:count]:
        if not isinstance(row, dict):
            continue
        number = _number(row.get("n"), 1, len(shown))
        if number is None:
            continue
        pair = shown[number - 1]
        if pair in chosen:
            continue
        if pair.chapter:
            # Заголовок главы — уже готовая тема куска, так её назвал сам
            # автор ролика. Прогон на живых роликах показал: модель при
            # переписывании систематически даёт вариант хуже (3 из 6 надписей
            # стали слабее, ни одна не стала сильнее) — не трогаем, ответ
            # модели в title для этой пары не используем.
            if on_note:
                on_note(f"  надпись не менялась (есть глава): {pair.hook}")
        elif (round(pair.start, 2), round(pair.end, 2)) in authored:
            if on_note:
                on_note(f"  надпись не менялась (вопрос ведущего): {pair.hook}")
        else:
            # Пары без хука вообще (не глава, не вопрос) — переписывание
            # моделью остаётся единственным рабочим путём получить надпись.
            pair.hook = _clean_title(row.get("title"), pair.hook, pair.text[:300])
        pair.score = round(float(row.get("score") or 0), 2)
        chosen.append(pair)
        if on_note:
            on_note(f"  взяла: {pair.hook} — {row.get('why') or ''}")

    # Меньшая модель просьбу «выбери {count}» иногда читает как верхнюю
    # границу и останавливается на одном явном фаворите — на живом прогоне
    # qwen2.5 из 18 пар выбрала одну вместо пяти. Промпт теперь прямо
    # разрешает добор, но полагаться только на послушание модели нельзя:
    # довыбираем сами из головы списка (он уже отсортирован своим счётом).
    for pair in shown:
        if len(chosen) >= count:
            break
        if pair in chosen:
            continue
        chosen.append(pair)
        if on_note:
            on_note(f"  добрала: {pair.hook} (своим счётом, модель недодала)")

    return chosen


