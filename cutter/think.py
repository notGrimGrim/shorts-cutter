# Расход токенов за последнюю минуту — общий на весь процесс. Считать его
# отдельно в каждом вызове нельзя: у Groq лимит один на ключ, и второй
# ролик подряд получал 429 на первом же запросе, потому что свой счётчик
# начинал с нуля, а серверный помнил всё.
_LOG = []


class _Meter:
    """Учёт отправленного за минуту и паузы, когда окно исчерпано.

    Токены общие на процесс, а терпение своё у каждого разбора: ждать
    квоту ради одного ролика бесконечно нельзя.
    """

    def __init__(self, on_note=None):
        self.waited = 0.0
        self.on_note = on_note

    @staticmethod
    def _spent():
        now = time.time()
        _LOG[:] = [row for row in _LOG if now - row[0] < 60.0]
        return sum(row[1] for row in _LOG)

    def hold(self, pause, why=""):
        """Пауза, если она укладывается в бюджет. False — терпение вышло."""
        pause = max(1.0, min(pause, 61.0))
        if self.waited + pause > WAIT_BUDGET:
            return False
        if self.on_note:
            self.on_note(f"{why or 'квота модели исчерпана'}, жду {pause:.0f} с")
        time.sleep(pause)
        self.waited += pause
        return True

    def room_for(self, tokens):
        """Ждёт, пока освободится место. False — ждать дольше нельзя."""
        while self._spent() + tokens > PER_MINUTE:
            oldest = _LOG[0][0] if _LOG else time.time()
            if not self.hold(61.0 - (time.time() - oldest),
                             "минутная квота модели исчерпана"):
                return False
        return True

    @staticmethod
    def note(tokens):
        _LOG.append((time.time(), tokens))


class _Stop(RuntimeError):
    """Дальше спрашивать нельзя: квота, отказ или кончилось терпение."""


def _guess_tokens(text):
    """Грубая оценка: на русском выходит около трёх знаков на токен."""
    return int(len(text) / 3) + 200


# В отказе по лимиту Groq пишет, через сколько можно повторить:
# «Please try again in 47.463s». Это точнее нашего счёта — он идёт
# по ответам сервера и всегда чуть отстаёт.
_AGAIN = re.compile(r"try again in ([\d.]+)s")


def _ask(prompt, meter, answer_tokens=ANSWER_TOKENS):
    """Один вопрос модели. Возвращает разобранный JSON или None.

    Ключей может быть несколько. Упёрлись в суточную квоту одного —
    переходим на следующий и повторяем тот же вопрос: для нас это тот же
    Groq, просто с другой квотой.
    """
    if not meter.room_for(_guess_tokens(prompt) + answer_tokens):
        raise _Stop("время ожидания квоты вышло")

    body = _dumps({
        "model": MODEL,
        "messages": [
            {
                "role": "system",
                "content": "Ты монтажёр вертикальных шортсов из интервью. "
                           "Отвечаешь только объектом JSON, без пояснений.",
            },
            {"role": "user", "content": prompt},
        ],
        "temperature": 0,
        "max_completion_tokens": answer_tokens,
        "reasoning_effort": EFFORT,
        "response_format": {"type": "json_object"},
    }, ensure_ascii=False).encode("utf-8")

    reply = None
    # Попыток столько, сколько ключей, плюс одна на паузу по минутной квоте.
    for attempt in range(len(cloud.keys()) + 2):
        token = cloud.key()
        if not token:
            raise _Stop("ключей Groq не осталось")

        request = urllib.request.Request(
            URL, data=body,
            headers={
                "Authorization": f"Bearer {token}",
                "Content-Type": "application/json",
                # Cloudflare перед Groq рубит запрос без представления — тот
                # же случай, что и с расшифровкой, см. cloud.AGENT.
                "User-Agent": cloud.AGENT,
            },
        )

        try:
            with urllib.request.urlopen(request, timeout=TIMEOUT) as answer:
                reply = _loads(answer.read().decode("utf-8"))
            break
        except urllib.error.HTTPError as error:
            detail = error.read().decode("utf-8", "replace")[:200]
            if error.code == 429:
                # Суточную квоту пережидать нечем: до сброса часы, а не
                # секунды. Берём следующий ключ, а если его нет — уходим.
                if "per day" in detail or "TPD" in detail:
                    if cloud.drop_key(token, meter.on_note):
                        continue
                    raise _Stop("суточная квота модели на сегодня выбрана") from None

                asked = _AGAIN.search(detail)
                pause = float(asked.group(1)) + 1.0 if asked else 61.0
                if meter.hold(pause, "модель просит подождать"):
                    # Раз сервер назвал время сам — после паузы его окно
                    # свободно, и наши записи о минуте больше не нужны.
                    _LOG.clear()
                    continue
                raise _Stop(f"лимит модели исчерпан: {detail}") from None
            if error.code in (401, 403):
                # Ключ не приняли — возможно, он просто протух. Если есть
                # запасной, пробуем им, а не роняем весь разбор.
                if cloud.drop_key(token, meter.on_note):
                    continue
                raise _Stop("Groq не принял ключ") from None
            # Модель не смогла собрать JSON — это про один кусок, а не про всё.
            if error.code == 400:
                return None
            raise _Stop(f"Groq ответил {error.code}: {detail}") from None
        except (urllib.error.URLError, OSError) as error:
            raise _Stop(f"до Groq не достучаться: {error}") from None

    if reply is None:
        raise _Stop("Groq не ответил ни по одному ключу")

    meter.note(reply.get("usage", {}).get("total_tokens", 0))

    try:
        return _loads(reply["choices"][0]["message"]["content"])
    except (KeyError, IndexError, ValueError, TypeError):
        return None


SYSTEM = ("Ты монтажёр вертикальных шортсов из интервью. "
          "Отвечаешь только объектом JSON, без пояснений.")


def anyone(on_note=None):
    """Кто сегодня думает: 'groq', 'local' или пусто, если никто."""
    if cloud.ready():
        return "groq"
    if local.ready():
        return "local"
    return ""


def _ask_any(prompt, meter, answer_tokens=ANSWER_TOKENS, on_note=None):
    """Вопрос тому, кто доступен: сначала Groq, потом модель на этой машине.

    Groq умнее и быстрее, но конечен. Когда его квота выбрана, вопрос уходит
    в Ollama — она медленнее и проще, зато без лимитов. Не отвечает никто —
    бросает _Stop, и вызывающий решает сам, что дальше (см. judge()/rank()).
    """
    if cloud.ready():
        try:
            return _ask(prompt, meter, answer_tokens)
        except _Stop as stop:
            if not local.ready():
                raise
            if on_note:
                on_note(f"{stop} — спрашиваю модель на этой машине")

    if local.ready():
        return local.ask(prompt, SYSTEM, answer_tokens)

    raise _Stop("спрашивать некого: нет ни ключа Groq, ни локальной модели")


